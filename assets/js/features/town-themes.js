const THEME_COLORS = {
  d: "#65432f", w: "#fff5db", r: "#c75045", g: "#3d9b5b",
  y: "#f2c64f", b: "#58bde5", p: "#ee9bbb",
};

function themeSprite(name, x, y) {
  return '<g transform="translate(' + x + " " + y + ')">' +
    THEME_PIXELS[name].replaceAll(" ", "").match(/.{8}/g).map((row, py) =>
      [...row].map((pixel, px) =>
        pixel === "." ? "" : R(px * 4, py * 4, 4, 4, THEME_COLORS[pixel]),
      ).join(""),
    ).join("") + "</g>";
}
