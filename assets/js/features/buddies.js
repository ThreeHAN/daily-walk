function dk(h, f) {
  const n = parseInt(h.slice(1), 16),
    m = 1 - f;
  return (
    "#" +
    [(n >> 16) & 255, (n >> 8) & 255, n & 255]
      .map((v) =>
        Math.round(v * m)
          .toString(16)
          .padStart(2, "0"),
      )
      .join("")
  );
}
